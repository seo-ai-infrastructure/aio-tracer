def cite(ref: str) -> dict:
    """``"US11769017B1#linkifying_engine"`` or ``"finding:pricing_from_blog"`` -> citation dict."""
    if ref.startswith("finding:"):
        return FINDINGS[ref.split(":", 1)[1]].cite()
    number, _, passage = ref.partition("#")
    return PATENTS[number].cite(passage or None)


def bibliography() -> dict:
    return {
        "patents": [{k: v for k, v in asdict(p).items() if k != "passages"} for p in PATENTS.values()],
        "course_findings": [asdict(f) for f in FINDINGS.values()],
        "disclaimer": (
            "Patents describe disclosed mechanisms, not confirmed production behaviour. None of the cited "
            "patents names Google Business Profile, reviews, or the Knowledge Graph; GBP-layer attribution "
            "is a heuristic mapping onto the patents' generic SRD model."
        ),
    }
