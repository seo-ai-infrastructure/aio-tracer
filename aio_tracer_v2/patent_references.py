"""Primary-source reference registry: Google patents + Apex Course DOM findings.

Every attribution and evidence check in this tool cites an entry from this module, so each
output row can be traced to (a) the DOM bytes it came from and (b) the documented mechanism
that justifies interpreting those bytes a certain way.

Patent passages below were copied from the patent full text on patents.google.com (fetched
2026-10-06). They describe what Google *disclosed it may do*; a patent is not proof that
production AI Overviews do it. Nothing in these patents mentions Google Business Profile,
reviews, or the Knowledge Graph by name — the GBP layer taxonomy used by
:mod:`attribution_engine` is a heuristic that sits *on top of* the patents' generic
"search result document (SRD)" model, and is graded accordingly.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass, field
from typing import Optional


@dataclass(frozen=True)
class PatentReference:
    key: str
    number: str
    title: str
    assignee: str
    filed: str
    published_or_granted: str
    url: str
    passages: dict = field(default_factory=dict)

    def cite(self, passage_key: Optional[str] = None) -> dict:
        out = {"source_type": "patent", "number": self.number, "title": self.title, "url": self.url}
        if passage_key:
            out["passage_key"] = passage_key
            out["passage"] = self.passages[passage_key]
        out["policy"] = "Disclosed mechanism, not evidence of production AIO behavior or source provenance."
        return out


@dataclass(frozen=True)
class CourseFinding:
    key: str
    document: str
    section: str
    grade: str  # "confirmed" | "hypothesis"
    statement: str

    def cite(self) -> dict:
        return {"source_type": "legacy_course_reference", **asdict(self), "verification_status": "Original PDFs not bundled; reference not independently verified by AIO Tracer"}


